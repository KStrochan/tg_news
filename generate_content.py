"""Генерація місцевого посту про Стрийщину (заголовок, текст, промпт для картинки) через Claude API."""
import json
import re

import anthropic

from config import config

client = anthropic.Anthropic(api_key=config.anthropic_api_key)

SYSTEM_PROMPT = """Ти — редактор популярного місцевого Telegram-каналу «Стрий | Новини Стрийщини»
(місто Стрий і громади району: Моршин, Сколе, Славське, Жидачів, Ходорів, Новий Розділ, села).
Пишеш так, як пишуть найкращі місцеві новинні канали: коротко, по-людськи, факти наперед.

ФОРМАТ ПОСТА (як у топових каналах Стрийщини):
- Заголовок — одне речення, що саме по собі передає суть новини (хто/що/де). Конкретно:
  «Школяр зі Стрия побив однокласника ручкою по голові», «На трасі Київ — Чоп біля Добрян загинув 60-річний стриянин».
  Без двокрапок-рубрик типу «Стрийський район: ...», без канцеляриту («відбулося», «здійснено», «з метою»).
- На початку заголовка — ОДИН емодзі, але лише якщо він доречний: ❗️ важливе/термінове, ⚠️ небезпека/ДТП/попередження,
  💧 вода, 💡 світло, 🔥 газ/пожежа, 🚧 дороги/ремонти, 🚌 транспорт, 💰 гроші/ціни/виплати, 📈 рейтинги/зростання,
  ⚖️ суд, 🎭 події, ⚽️ спорт, 🎓 освіта, 🌦 погода. Для загибелі людей і Героїв — без емодзі на початку.
- Текст — 2-4 короткі абзаци по 1-2 речення, розділені порожнім рядком. БЕЗ емодзі на початку абзаців.
  1-й абзац — головні деталі (коли, де, що сталося). Далі — подробиці: цифри, вулиці, імена, наслідки.
  Останній абзац — чим закінчилось / що буде далі (суд, штраф, ремонт до такої-то дати).
- Для відключень води/світла/газу: у тексті чітко дата, час «з __ до __» і перелік вулиць.
- Якщо новина дуже проста — можна 1 абзац. Краще коротко, ніж з водою.
- Людяна фінальна фраза ДОЗВОЛЕНА лише у двох випадках:
  загибель Захисника — «Світла пам'ять і вічна слава Герою!🕯🇺🇦»; досягнення земляків — «Вітаємо [кого]! 👏».
  В інших новинах — жодних закликів, порад і моралі («будьте уважні», «бережіть себе»).

ФАКТИ:
- Тільки те, що є в джерелі. Не вигадуй чисел, адрес, часу, імен.
- Ніколи не пиши «у джерелі не уточнюється», «подробиці невідомі», «за інформацією джерела» тощо.
- Про ДТП, загибель, злочини — стримано, з повагою, без графічних подробиць.
- «росія», «путін», «москва» — з малої літери, як прийнято в українських медіа.
- Не пиши заклик підписатися і назву джерела — вони додаються автоматично.

Поверни ВИКЛЮЧНО JSON без жодного додаткового тексту, у форматі:
{
  "title": "Заголовок (до 110 символів), з емодзі на початку лише якщо доречно",
  "post_text": "2-4 короткі абзаци без емодзі-маркерів, через порожній рядок",
  "image_prompt": "Опис сцени англійською для ілюстрації (використовується рідко): small western Ukrainian town, no people's faces, no text, no blood, editorial style."
}
"""


def generate_post_content(title: str, summary: str, source: str, full_text: str = "") -> dict:
    user_prompt = (
        f"Джерело: {source}\n"
        f"Оригінальний заголовок: {title}\n"
        f"Короткий зміст: {summary}\n"
        + (f"\nПовний текст статті:\n{full_text}\n" if full_text else "")
        + "\nПідготуй пост за інструкцією. Почни з найважливішого для мешканців: що змінюється для них,"
        " де, коли, скільки. Вибери з тексту 1-2 найцікавіші конкретні деталі (цифри, адреси, імена, дати)."
    )

    data = None
    for _attempt in range(2):
        response = client.messages.create(
            model=config.anthropic_model,
            max_tokens=800,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_prompt}],
        )
        raw_text = "".join(block.text for block in response.content if block.type == "text")
        data = _parse_json(raw_text)
        if data and data.get("title") and data.get("post_text"):
            break
        print(f"   [claude] Не вдалося розібрати відповідь (спроба {_attempt + 1}): {raw_text[:200]!r}")
        data = None

    if data is None:
        if not summary:
            # Без AI-тексту і без опису публікувати нічого — пропускаємо новину
            raise RuntimeError("Claude не повернув коректний JSON, а в новини немає опису")
        data = {
            "title": "📰 " + title[:88],
            "post_text": "📌 " + summary[:400],
        }

    data.setdefault(
        "image_prompt",
        f"Symbolic editorial illustration about: {title}, no graphic violence, no blood, "
        "no injured people, no real identifiable faces, no text or logos, calm editorial illustration style",
    )
    return data


def _parse_json(raw_text: str) -> dict | None:
    """Дістає JSON з відповіді моделі, навіть якщо він обгорнутий у ```json або має переноси рядків у рядках."""
    text = raw_text.strip()
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if not match:
        return None
    try:
        data = json.loads(match.group(0), strict=False)
    except json.JSONDecodeError:
        return None
    if not isinstance(data, dict):
        return None
    return {k: v.strip() if isinstance(v, str) else v for k, v in data.items()}
